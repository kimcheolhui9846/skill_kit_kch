def test_a_secret_in_an_allowed_section_blocks_the_whole_capture(kit, pc, workspace):
    """The last scan stops everything (exit 1); the report names file and line, not value."""
    path = pc / ".codex/AGENTS.md"
    path.write_text(path.read_text(encoding="utf-8") + f"\n- token {FAKE_GITHUB}\n", "utf-8")
    before = tree_digest(kit / "user", exclude=())
    code, out = kit_run(kit, workspace, "capture", "--write")
    assert code == EXIT_PARTIAL
    assert "user/codex/AGENTS.block.md: github token (line" in out
    assert FAKE_GITHUB not in out
    assert tree_digest(kit / "user", exclude=()) == before
    code, out = kit_run(kit, workspace, "capture", "--write", "--json")
    data = json.loads(out)
    assert data["written"] is False and data["secret_hits"][0]["kind"] == "github token"


def test_env_and_header_values_become_placeholders(kit, pc, workspace):
    rules = json.loads((kit / capture.ALLOWLIST_REL).read_text(encoding="utf-8"))
    rules["codex"]["toml_tables"].append("mcp_servers.*")
    put(kit, capture.ALLOWLIST_REL, json.dumps(rules))
    code, out = kit_run(kit, workspace, "capture", "--write")
    assert code == EXIT_READY, out
    config = snapshot(kit)["user/codex/config.toml"]
    assert 'env = { CONTEXT7_API_KEY = "${ENV:CONTEXT7_API_KEY}" }' in config
    assert 'GITHUB_TOKEN = "${ENV:GITHUB_TOKEN}"' in config
    assert 'command = "${HOME}/.codex/tools/npx.cmd"' in config
    assert secrets_in(config) == []


def test_the_kit_block_is_not_captured_back(kit, pc, workspace):
    path = pc / ".claude/CLAUDE.md"
    block = "<!-- hackathon-kit:begin -->\nKIT TEXT\n<!-- hackathon-kit:end -->\n"
    path.write_text(path.read_text(encoding="utf-8") + "\n" + block, "utf-8")
    kit_run(kit, workspace, "capture", "--write", "--agent", "claude")
    text = snapshot(kit)["user/claude/CLAUDE.block.md"]
    assert "KIT TEXT" not in text and "hackathon-kit" not in text
    assert "Commit as the user." in text


def test_agent_option_limits_what_is_read(kit, pc, workspace):
    kit_run(kit, workspace, "capture", "--write", "--agent", "codex")
    assert all(rel.startswith("user/codex/") for rel in snapshot(kit))


