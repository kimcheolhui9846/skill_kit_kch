def snapshot(kit: Path) -> dict:
    root = kit / "user"
    return {
        p.relative_to(kit).as_posix(): p.read_text(encoding="utf-8")
        for p in root.rglob("*")
        if p.is_file() and p.name != "capture-allowlist.json"
    }


def test_dry_run_writes_nothing(kit, pc, workspace):
    """TC-USR-07: the default is a dry run."""
    before = tree_digest(kit / "user", exclude=())
    code, out = kit_run(kit, workspace, "capture")
    assert code == EXIT_READY, out
    assert "CREATE" in out and "user/codex/AGENTS.block.md" in out
    assert "DRY RUN: nothing was written" in out
    assert tree_digest(kit / "user", exclude=()) == before


def test_write_creates_a_snapshot_with_templates_only(kit, pc, workspace):
    """TC-USR-01: ${HOME} only; no absolute path, no user name."""
    code, out = kit_run(kit, workspace, "capture", "--write")
    assert code == EXIT_READY, out
    files = snapshot(kit)
    assert sorted(files) == sorted(
        capture.SNAPSHOT_FILES["codex"] + capture.SNAPSHOT_FILES["claude"]
    )
    for rel, text in files.items():
        assert USER not in text, rel
        assert str(pc) not in text and pc.as_posix() not in text, rel
    assert "${HOME}\\tools" in files["user/codex/AGENTS.block.md"]
    assert "${HOME}\\runpod-hf-harness" in files["user/claude/CLAUDE.block.md"]
    assert USER not in out and str(pc) not in out


def test_capture_never_takes_secrets_or_excluded_state(kit, pc, workspace):
    """TC-USR-08: auth, history, sqlite, sessions, projects.*, connector ids, env values."""
    code, out = kit_run(kit, workspace, "capture", "--write")
    assert code == EXIT_READY, out
    every = "\n".join(snapshot(kit).values())
    assert secrets_in(every) == [] and secrets_in(out) == []
    for word in (
        "projects",
        "connector_",
        "trusted_hash",
        "oauthAccount",
        "alice@example.com",
        "Desktop",
        "private notes",
        "computer-use",
        "autoMode",
        "theme",
        "gpt-x",
    ):
        assert word not in every, word
    agents = snapshot(kit)["user/codex/AGENTS.block.md"]
    assert "## Windows command execution" in agents and "## not a section" in agents
    assert "Project Workspace Registry" not in agents
    assert "[projects.*] left out (1 table(s))" in out
    assert "top-level keys are not carried (set them by hand): model, developer_instructions" in out
    config = snapshot(kit)["user/codex/config.toml"]
    assert userscope.table_names(config) == ["features", 'plugins."browser@openai-bundled"']


def test_names_only_for_mcp_and_inventory(kit, pc, workspace):
    kit_run(kit, workspace, "capture", "--write")
    files = snapshot(kit)
    codex = json.loads(files["user/codex/mcp.json"])["servers"]
    assert codex == [{"name": "context7"}, {"name": "playwright"}]
    claude = json.loads(files["user/claude/mcp.json"])["servers"]
    assert claude == [
        {"name": "context7", "transport": "http"},
        {"name": "playwright", "transport": "stdio"},
    ]
    inv = json.loads(files["user/codex/inventory.json"])
    skills = {r["name"]: r["origin"] for r in inv["skills"]}
    assert skills == {
        "mystery": "unknown origin (not carried)",
        "ralph": "omx (differs from v0.21.46)",
    }
    assert inv["agents"] == [
        {"name": "analyst.toml", "origin": "generated by omx setup (not carried)"}
    ]


