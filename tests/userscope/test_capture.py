# Upstream example values, not secrets. "eyJhbGciOiJIUzI1NiIs" is the base64 of the JWT header
# fragment {"alg":"HS256", followed by "..." (eng-patterns pack, 2026-11-08).
KNOWN_PLACEHOLDERS = [("third_party/affaan-m-ECC/skills/api-design/SKILL.md", "bearer token", 303)]


def test_repo_user_and_third_party_have_no_secrets():
    hits = []
    for folder in ("user", "third_party"):
        for path in sorted((KIT_ROOT / folder).rglob("*")):
            if path.is_file():
                try:
                    text = path.read_text(encoding="utf-8")
                except UnicodeDecodeError:
                    continue
                hits += capture.scan(path.relative_to(KIT_ROOT).as_posix(), text)
    assert [hit for hit in hits if hit not in KNOWN_PLACEHOLDERS] == []


@pytest.mark.parametrize(
    "line,hit",
    [
        ("Authorization: Bearer abcdefgh12345678", "bearer token"),
        ('MY_TOKEN = "abcdef123456"', "token/secret assignment"),
        ("export DB_PASSWORD=hunter2hunter2", "token/secret assignment"),
        ("Authorization: Bearer ${ENV:CTX_KEY}", None),
        ('CONTEXT7_API_KEY = "${ENV:CONTEXT7_API_KEY}"', None),
        ("const TOKEN = generateToken()", None),
    ],
)
def test_extra_patterns_catch_literal_values_only(line, hit):
    found = [label for _, label, _ in capture.scan("x.md", line)]
    assert found == ([hit] if hit else [])
