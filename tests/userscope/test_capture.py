@pytest.mark.parametrize(
    "line,name",
    [
        ("[features]", "features"),
        ('[plugins."a@b"]', 'plugins."a@b"'),
        ('[ hooks . state."x#hooks[0]:stop" ]  # c', 'hooks.state."x#hooks[0]:stop"'),
        ("[[profiles.list]]", "profiles.list"),
        ('["a", "b"]', None),  # an array line, not a table
        ("[a] = 1", None),
        ("args = [1]", None),
    ],
)
def test_toml_headers(line, name):
    assert userscope.header(line) == name


def test_multiline_strings_hide_headers():
    text = 'x = """\n[inside]\n"""\n[real]\nk = 1\n'
    assert userscope.table_names(text) == ["real"]


